/**
 * Writes nginx 301s from the old /articles/<slug>/ URLs to the new
 * /<category>/<slug>/ ones.
 *
 * Those old URLs are indexed. A static export cannot redirect by itself, so
 * without these nginx would serve 404s and the accumulated ranking would be lost.
 * Regenerate whenever an article is added or changes category:
 *
 *   node scripts/gen-article-redirects.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const CAT = {
  security: 'security-and-cameras', lighting: 'lighting', energy: 'energy-and-solar',
  entertainment: 'entertainment-and-audio', climate: 'climate-and-comfort',
  'hubs-and-platforms': 'hubs-and-platforms', 'robot-vacuums': 'robot-vacuums',
  'setup-guides': 'setup-guides', 'buying-guides': 'buying-guides',
};

const dir = path.join(process.cwd(), 'content', 'articles');
const lines = ['# Generated by scripts/gen-article-redirects.mjs — do not edit by hand.'];

for (const file of fs.readdirSync(dir).filter((f) => /\.mdx?$/.test(f))) {
  const { data } = matter(fs.readFileSync(path.join(dir, file), 'utf8'));
  if (data.draft) continue;
  const slug = file.replace(/\.mdx?$/, '');
  const cat = CAT[data.category];
  if (!cat) continue;
  lines.push(`location = /articles/${slug}/ { return 301 /${cat}/${slug}/; }`);
  lines.push(`location = /articles/${slug} { return 301 /${cat}/${slug}/; }`);
}

const out = '/etc/nginx/snippets/nxtsmarthome-article-redirects.conf';
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${(lines.length - 1) / 2} redirects to ${out}`);
