/**
 * scripts/prune-fabricated-products.mjs
 *
 * Removes generated content from public/data/products.json:
 *
 *   1. Fabricated variants — the "-pro", "-ultra", "-gen-4" and "-gen-5"
 *      slugs. These are not real SKUs. Google Shopping returns nothing for
 *      them, and every enrichment they carry (image, specs, reviews, prices)
 *      actually belongs to the base product, which made them read as more
 *      legitimate than they are.
 *
 *   2. Templated pros/cons — all 350 records carried one identical pros array
 *      and one identical cons array, so they conveyed nothing per-product and
 *      presented generic filler as editorial judgement.
 *
 *   node scripts/prune-fabricated-products.mjs [--dry-run]
 *
 * `bestFor` is kept: it is unique per base product and is the verdict that
 * CLAUDE.md rule 3 requires a published product to carry.
 *
 * Writes scratch/variant-redirects.map so the removed URLs can be 301'd to
 * their base product rather than left to 404.
 */

import fs from 'node:fs';
import path from 'node:path';

const PRODUCTS_JSON = path.join(process.cwd(), 'public/data/products.json');
const REDIRECT_MAP = path.join(process.cwd(), 'scratch/nxtsmarthome-variant-redirects.conf');
const VARIANT_RE = /-(pro|ultra|gen-\d+)$/;

const dryRun = process.argv.includes('--dry-run');

const products = JSON.parse(fs.readFileSync(PRODUCTS_JSON, 'utf8'));
const allSlugs = new Set(products.map((p) => p.slug));

/*
 * A trailing "-ultra" or "-pro" is only a fabricated suffix when stripping it
 * leaves a product that actually exists. Bose really does sell a "Smart
 * Soundbar Ultra" — there is no "bose-smart-soundbar" for it to be a variant
 * of — so it is a base product, while "…-ultra-pro" and "…-ultra-ultra" are
 * generated on top of it. Matching the suffix alone would have deleted a real
 * product.
 */
function isFabricatedVariant(slug) {
  if (!VARIANT_RE.test(slug)) return false;
  return allSlugs.has(slug.replace(VARIANT_RE, ''));
}

const kept = [];
const removed = [];

for (const product of products) {
  if (isFabricatedVariant(product.slug)) removed.push(product);
  else kept.push(product);
}

const keptSlugs = new Set(kept.map((p) => p.slug));
const orphans = removed.filter((p) => !keptSlugs.has(p.slug.replace(VARIANT_RE, '')));

let prosStripped = 0;
for (const product of kept) {
  if (product.pros || product.cons) prosStripped++;
  delete product.pros;
  delete product.cons;
}

console.log(`products      : ${products.length} → ${kept.length}`);
console.log(`variants removed: ${removed.length}`);
console.log(`pros/cons stripped from: ${prosStripped} records`);
if (orphans.length) {
  console.log(`⚠️  ${orphans.length} variants have no surviving base product:`);
  for (const o of orphans.slice(0, 10)) console.log(`     ${o.slug}`);
}

if (dryRun) {
  console.log('\n🧪 --dry-run: nothing written');
  process.exit(0);
}

/*
 * Matches the format of nxtsmarthome-article-redirects.conf: an exact-match
 * location per URL, with and without the trailing slash. These pages are live
 * and may be indexed, so they 301 to the base product rather than 404.
 */
const lines = ['# Generated by scripts/prune-fabricated-products.mjs — do not edit by hand.'];
let redirectCount = 0;
for (const p of removed) {
  const base = p.slug.replace(VARIANT_RE, '');
  if (!keptSlugs.has(base)) continue;
  const target = `/products/${base}/`;
  lines.push(`location = /products/${p.slug}/ { return 301 ${target}; }`);
  lines.push(`location = /products/${p.slug} { return 301 ${target}; }`);
  redirectCount++;
}

fs.mkdirSync(path.dirname(REDIRECT_MAP), { recursive: true });
fs.writeFileSync(REDIRECT_MAP, `${lines.join('\n')}\n`, 'utf8');
fs.writeFileSync(PRODUCTS_JSON, `${JSON.stringify(kept, null, 2)}\n`, 'utf8');

console.log(`\n✅ products.json rewritten with ${kept.length} products`);
console.log(`✅ ${redirectCount} redirects written to ${path.relative(process.cwd(), REDIRECT_MAP)}`);
