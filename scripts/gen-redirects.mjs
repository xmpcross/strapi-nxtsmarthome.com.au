/**
 * Writes public/_redirects and public/_headers for a static host
 * (Cloudflare Pages, Workers static assets, Netlify — all read the same files),
 * plus public/_redirects.map, the same rules as an nginx map for the self-hosted
 * origin. The vhost includes that file straight out of the web root, so the
 * rules still travel with the repository rather than living in /etc/nginx.
 *
 *   node scripts/gen-redirects.mjs
 *
 * This replaces the nginx snippets the site used to rely on. A static export
 * cannot redirect by itself, so when the site moved off nginx every one of
 * these 301s stopped existing and the old URLs began answering 404 — which is
 * exactly what happened, and why these now live in the repository instead of
 * in /etc/nginx/snippets where a host change could not carry them.
 *
 * Two sources:
 *
 *   1. Article moves — derived from content/articles, the same way
 *      gen-article-redirects.mjs derives the nginx version. Regenerating after
 *      adding an article or changing its category keeps them in step.
 *   2. Product-variant consolidations — a static list, since the variants no
 *      longer exist anywhere to be derived from.
 *
 * Run it as part of prebuild so the files can never drift from the content.
 */
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const ROOT = process.cwd();
const PUBLIC_DIR = path.join(ROOT, 'public');

// Frontmatter uses the category key; the URL uses its slug. Same mapping as
// lib/site.ts — see gen-article-redirects.mjs.
const CATEGORY_SLUG = {
  security: 'security-and-cameras',
  lighting: 'lighting',
  energy: 'energy-and-solar',
  entertainment: 'entertainment-and-audio',
  climate: 'climate-and-comfort',
  'hubs-and-platforms': 'hubs-and-platforms',
  'robot-vacuums': 'robot-vacuums',
  'setup-guides': 'setup-guides',
  'buying-guides': 'buying-guides',
};

const VARIANTS_FILE = path.join(ROOT, 'content', 'product-variant-redirects.txt');

function articleRedirects() {
  const dir = path.join(ROOT, 'content', 'articles');
  const lines = [];

  for (const file of fs.readdirSync(dir).filter((f) => /\.mdx?$/.test(f))) {
    const { data } = matter(fs.readFileSync(path.join(dir, file), 'utf8'));
    if (data.draft) continue;

    const slug = file.replace(/\.mdx?$/, '');
    const category = CATEGORY_SLUG[data.category];
    if (!category) continue;

    // Both forms: the site sets trailingSlash, but indexed links exist without.
    lines.push(`/articles/${slug} /${category}/${slug}/ 301`);
    lines.push(`/articles/${slug}/ /${category}/${slug}/ 301`);
  }

  return lines;
}

/** `<old-path> <new-path>` per line; blank lines and # comments ignored. */
function variantRedirects() {
  if (!fs.existsSync(VARIANTS_FILE)) return [];

  return fs
    .readFileSync(VARIANTS_FILE, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .flatMap((line) => {
      const [from, to] = line.split(/\s+/);
      if (!from || !to) return [];
      return [`${from.replace(/\/$/, '')} ${to} 301`, `${from.replace(/\/$/, '')}/ ${to} 301`];
    });
}

const articles = articleRedirects();
const variants = variantRedirects();

const redirects = [
  '# Generated by scripts/gen-redirects.mjs — do not edit by hand.',
  '#',
  '# Cloudflare Pages allows 2,000 static rules; Netlify has no practical limit.',
  '# Order matters: the first match wins.',
  '',
  '# Articles moved from /articles/<slug>/ to /<category>/<slug>/.',
  ...articles,
  '',
  '# Product variants consolidated onto a single canonical product.',
  ...variants,
  '',
].join('\n');

// Replaces the add_header lines the nginx vhost used to set. Without these the
// site loses its security headers entirely on a static host.
const headers = `# Generated by scripts/gen-redirects.mjs — do not edit by hand.

/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: SAMEORIGIN
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()

# Build assets carry a content hash in the filename, so they can be cached
# forever — a changed file gets a different name.
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/covers/*
  Cache-Control: public, max-age=2592000

/sitemap.xml
  Cache-Control: public, max-age=3600

/search-index.json
  Cache-Control: public, max-age=3600
`;

// The nginx form of the same rules. Included from inside a `map $uri` block in
// the vhost, so each line is `"<from>" "<to>";` — anything else fails nginx -t,
// which deploy.sh runs before reloading, so a bad file cannot go live.
const nginxMap = [
  '# Generated by scripts/gen-redirects.mjs — do not edit by hand.',
  '#',
  '# Included from map $uri $nxtsmarthome_redirect in the nxtsmarthome.com.au vhost.',
  '',
  ...[...articles, ...variants].map((rule) => {
    const [from, to] = rule.split(/\s+/);
    return `"${from}" "${to}";`;
  }),
  '',
].join('\n');

fs.mkdirSync(PUBLIC_DIR, { recursive: true });
fs.writeFileSync(path.join(PUBLIC_DIR, '_redirects'), redirects);
fs.writeFileSync(path.join(PUBLIC_DIR, '_headers'), headers);
fs.writeFileSync(path.join(PUBLIC_DIR, '_redirects.map'), nginxMap);

const total = articles.length + variants.length;
console.log(`wrote public/_redirects — ${total} rules (${articles.length} article, ${variants.length} variant)`);
console.log('wrote public/_headers');
console.log(`wrote public/_redirects.map — ${total} nginx map entries`);

if (total > 2000) {
  console.warn(`warning: ${total} rules exceeds Cloudflare Pages' 2,000 static-rule limit.`);
}
